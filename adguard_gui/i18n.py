def set_lang(code: str) -> None:
    global _current_lang
    if code in {c for c, _ in LANGUAGES}:
        _current_lang = code
    else:
        _current_lang = _DEFAULT_LANG


def current_lang() -> str:
    return _current_lang


def supported_codes() -> set[str]:
    return {c for c, _ in LANGUAGES}


def detect_system_lang() -> str:
    """Подбирает поддерживаемый язык под локаль системы.

    Используется при первом запуске (когда config.json ещё нет).
    Порядок проверки:
        1. ``QLocale.system().name()`` / ``uiLanguages()``
        2. ``$LC_ALL`` / ``$LC_MESSAGES`` / ``$LANG``
        3. Возврат английского, если ничего не подошло.
    """
    codes = supported_codes()
    candidates: list[str] = []

    # 1) Qt locale — самый надёжный источник для GUI-приложения.
    try:
        from PySide6.QtCore import QLocale
        loc = QLocale.system()
        candidates.extend(loc.uiLanguages())
        candidates.append(loc.name())
    except Exception:
        pass

    # 2) Переменные окружения POSIX.
    import os
    for env in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"):
        val = os.environ.get(env, "")
        if val:
            candidates.extend(val.split(":"))

    for raw in candidates:
        if not raw:
            continue
        # Нормализация: "ru_RU.UTF-8" / "ru-RU" / "ru" → "ru".
        token = raw.replace("-", "_").split(".", 1)[0].split("@", 1)[0]
        base = token.split("_", 1)[0].lower()
        # Особый случай для китайского: "zh_CN" / "zh-Hans" — оба сводим к "zh".
        if base in codes:
            return base

    return _DEFAULT_LANG


def tr(key: str, **kwargs) -> str:
    if _current_lang == _DEFAULT_LANG:
        text = key
    else:
        text = TRANSLATIONS.get(_current_lang, {}).get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text
